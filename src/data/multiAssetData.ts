const SEP_16_START = Math.floor(new Date('2026-09-16T00:00:00Z').getTime() / 1000);
const SEP_17_START = Math.floor(new Date('2026-09-17T00:00:00Z').getTime() / 1000);
const SEP_18_START = Math.floor(new Date('2026-09-18T00:00:00Z').getTime() / 1000);

// Helper for generating forex candles
function generateForexCandles(
  baseStartPrice: number,
  volatility: number,
  trendDirection: number
): Candle[] {
  const candles: Candle[] = [];
  let currentTime = SEP_16_START;
  let price = baseStartPrice;

  for (let i = 0; i < 288 * 3; i++) {
    const open = price;
    const noise = (Math.sin(i * 0.15) + (Math.random() - 0.49)) * volatility;
    const close = open + (noise * 0.7) + (trendDirection * 0.00005);
    const high = Math.max(open, close) + Math.abs(noise * 0.6) + volatility * 0.2;
    const low = Math.min(open, close) - Math.abs(noise * 0.6) - volatility * 0.2;

    candles.push({
      time: currentTime,
      open: Number(open.toFixed(5)),
      high: Number(high.toFixed(5)),
      low: Number(low.toFixed(5)),
      close: Number(close.toFixed(5)),
      volume: Math.floor(1000 + Math.random() * 2500),
    });

    currentTime += 300;
    price = close;
  }
  return candles;
}

